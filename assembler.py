# Nova-8 / Nitro-8 Assembler
# Converts assembly code to hex machine code

INSTRUCTIONS = {
    'NOP':      '0000',
    'ADD':      '2000',
    'SUB':      '2100',
    'AND':      '2200',
    'OR':       '2300',
    'VSTORE_B': '6100',
    'INC':      '7000',
    'INC_B':    '7100',
    'HLT':      'F000',
}

INSTRUCTIONS_WITH_OPERAND = {
    'LOAD_A':   '10',
    'LOAD_B':   '11',
    'STORE':    '30',
    'JMP':      '40',
    'JZ':       '50',
    'VSTORE':   '60',
    'LOAD_RAM': '80',
    'SETBANK':  '90',
}

CLEAR_MACRO = [
    'LOAD_A 00',
    'LOAD_B 00',
    'VSTORE_B',
    'INC_B',
    'JZ 0B',
    'JMP 04',
]

def assemble(code):
    lines = code.strip().split('\n')
    expanded = []
    for line in lines:
        if line.strip().upper() == 'CLEAR':
            expanded.extend(CLEAR_MACRO)
        else:
            expanded.append(line)
    machine_code = []
    for line in expanded:
        line = line.strip()
        if not line or line.startswith(';'):
            continue
        parts = line.split()
        instruction = parts[0].upper()
        if instruction in INSTRUCTIONS:
            machine_code.append(INSTRUCTIONS[instruction])
        elif instruction in INSTRUCTIONS_WITH_OPERAND:
            operand = int(parts[1], 16)
            opcode = INSTRUCTIONS_WITH_OPERAND[instruction]
            machine_code.append(f'{opcode}{operand:02X}')
    return machine_code

def format_bank(machine_code):
    with_nops = []
    for code in machine_code:
        with_nops.append(code)
        with_nops.append('0000')
    while len(with_nops) < 256:
        with_nops.append('0000')
    rows = []
    for i in range(0, 256, 8):
        row = ' '.join(with_nops[i:i+8])
        rows.append(row)
    return '\n'.join(rows)

